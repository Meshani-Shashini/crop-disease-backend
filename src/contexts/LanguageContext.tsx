export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('language');
    return (saved as Language) || 'en';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('language', lang);
  };

  const t = (key: string): string => {
    if (!key) return '';
    
    const cleanKey = key.trim();
    
    // Check if key is AI prediction content
    if (language !== 'en' && aiResultTranslations[language]?.[cleanKey]) {
      return aiResultTranslations[language][cleanKey];
    }

    // Check if key is a dynamic database content
    if (language !== 'en' && contentTranslations[language]?.[cleanKey]) {
      return contentTranslations[language][cleanKey];
    }
    
    // Check if key is a static UI label
    if (uiTranslations[language]?.[cleanKey]) {
      return uiTranslations[language][cleanKey];
    }
    
    // Fallback to the key itself (which is in English)
    if (uiTranslations['en']?.[cleanKey]) {
      return uiTranslations['en'][cleanKey];
    }
    
    return key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
